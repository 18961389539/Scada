// Verify electrical state semantics and rendered symbols using the production factories and renderers.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const base = path.join(root, 'ScadaWeb/Mimics/PlgMimic/wwwroot/plugins/Mimic/js');
const plugin = path.join(root, 'ScadaWeb/Mimics/PlgMimBasicComp/wwwroot/plugins/MimBasicComp/js');
const scope = vm.createContext({console, document:{documentElement:{lang:'zh-Hans'}}, window:{}, setInterval, clearInterval, setTimeout, clearTimeout});
for (const name of ['mimic-common','mimic-descr','mimic-model','mimic-model-subtypes','mimic-factory','mimic-render']) vm.runInContext(fs.readFileSync(path.join(base,name+'.js'),'utf8'),scope);
for (const name of ['industrial','power-electrical']) vm.runInContext(fs.readFileSync(path.join(plugin,name+'.js'),'utf8'),scope);
const M = scope.rs.mimic, E = M.Electrical;
let checks=0;
function check(condition, message) {assert(condition,message); checks++; console.log('PASS '+message);}
const spec=fs.readFileSync(path.join(root,'ScadaWeb/Mimics/PlgMimBasicComp/Code/BasicComponentSpec.cs'),'utf8');
const scriptUrls=[...spec.matchAll(/"(~\/plugins\/MimBasicComp\/js\/[^\"]+)"/g)].map(m=>m[1]).sort();
check(scriptUrls.findIndex(s=>s.endsWith('/power-electrical.js')) > scriptUrls.findIndex(s=>s.endsWith('/industrial.js')),'Alphabetical runtime loading resolves electrical script dependencies');
const create = key => M.FactorySet.componentFactories.get('Industrial'+key).createComponent();
const runtime = {editMode:false, controlRight:false, mainApi:{dataPaused:false}};
const preview = {editMode:true};
const now=100000;
const c=create('CircuitBreaker');
c.properties.value=1;
let s=E.state(c,'CircuitBreaker',runtime,now);
check(s.position==='unknown' && s.energized===null,'Unbound runtime symbols never use editor preview values');
check(E.state(c,'CircuitBreaker',preview,now).position==='closed','Editor preview shows the configured switch position');
check(c.properties.clickAction.actionType===M.ActionType.NONE && c.properties.outCnlNum===0,'Electrical controls default to no output and no click command');
c.bindings={inCnlNum:204}; c.properties.energizedChannel=304;
function records(position, energy, positionStat=1, energyStat=1, age=0, extra={}) {
    c.customData={electrical:{readAt:now-age,records:{204:{val:position,stat:positionStat},304:{val:energy,stat:energyStat},...extra}}};
    return E.state(c,'CircuitBreaker',runtime,now);
}
s=records(1,0);
check(s.position==='closed' && s.energized===false,'Closed breaker can have valid deenergized feedback');
s=records(0,1);
check(s.position==='open' && s.energized===true,'Open breaker can still have energized feedback');
s=records(0,0);
check(s.position==='open' && s.energized===false,'Valid zero values represent open and deenergized feedback');
s=records(1,1,0,1);
check(s.position==='unknown' && s.energized===true,'Invalid position quality does not erase independent energy feedback');
s=records(1,1,1,0);
check(s.position==='closed' && s.energized===null,'Invalid energy quality never inherits the closed switch position');
s=records(0.3,0.3);
check(s.position==='unknown' && s.energized===null,'Unmapped analog values are not treated as boolean states');
s=records(NaN,Infinity);
check(s.position==='unknown' && s.energized===null,'Non-finite values cannot represent switch position or energy');
s=records(1,1,1,1,16000);
check(s.position==='unknown' && s.energized===null,'Feedback older than 15 seconds becomes unknown');
records(1,1);
s=E.state(c,'CircuitBreaker',{...runtime,mainApi:{dataPaused:true}},now);
check(s.position==='unknown' && s.energized===null,'Paused live data invalidates both electrical states');
s=records(2,0);
check(s.position==='trip' && s.energized===false,'A trip status is distinct from normal open feedback');
c.properties.tripChannel=205;
s=records(1,1,1,1,0,{205:{val:1,stat:1}});
check(s.position==='trip','Separate trip feedback overrides the position indication');
s=records(1,1,1,1,0,{205:{val:0,stat:0}});
check(s.position==='closed' && s.tripUnknown,'Missing trip quality is explicitly reported alongside valid position feedback');
check(E.markup('CircuitBreaker',c.properties,s).includes('跳闸反馈未知'),'Rendered state text exposes an unknown trip signal');
c.properties.tripChannel=0; c.properties.openValue=1; c.properties.closedValue=2; c.properties.tripValue=-1;
check(records(2,1).position==='closed' && records(1,1).position==='open','Double-point feedback supports separate 1=open and 2=closed codes');
check(records(0,1).position==='unknown' && records(3,1).position==='unknown','Double-point 0 and 3 remain unknown when trip code is disabled');
c.properties.closedValue=1;
check(records(1,1).position==='unknown','Conflicting open and closed mappings do not imply a known position');
c.properties.closedValue=2; c.properties.energizedValue=0; c.properties.deenergizedValue=1;
check(records(1,0).energized===true && records(1,1).energized===false,'Inverted energization feedback codes are configurable');
c.properties.label='<img src=x onerror=alert(1)>'; c.properties.vertical=false;
const html=E.markup('CircuitBreaker',c.properties,{position:'closed',energized:false,tripUnknown:false});
check(html.includes('&lt;img') && !html.includes('<img'),'Electrical labels and accessible descriptions escape HTML');
check(html.includes('rotate(90 50 50)') && html.includes('role="img"'),'Horizontal switches retain an accessible symbol description');
const bus=create('Busbar'); bus.bindings={inCnlNum:204}; bus.customData=c.customData;
check(E.state(bus,'Busbar',runtime,now).energized===true,'Busbar energy reads its actual input channel');
bus.properties.vertical=true;
check(E.markup('Busbar',bus.properties,{energized:null}).includes('rotate(90 50 50)'),'Busbars support vertical orientation');
const line=create('ElectricalLine'); line.properties.route='elbow'; line.properties.showJunction=true;
check(E.markup('ElectricalLine',line.properties,{energized:null}).includes('M50 0 V50 H100'),'Elbow conductors use continuous orthogonal segments');
check(E.markup('ElectricalLine',line.properties,{energized:null}).includes('stroke-dasharray="5 4"'),'Unknown energy is represented by dashed conductors');
line.properties.route='tee';
check(E.markup('ElectricalLine',line.properties,{energized:true}).includes('M0 50 H100 M50 50 V100'),'Tee conductors include an explicit branch');
check(E.markup('ElectricalLine',line.properties,{energized:true}).includes('class="el-junction"'),'Configured conductor junctions have a round connection dot independent of line proportions');
const ground=create('GroundSwitch');
check(E.markup('GroundSwitch',ground.properties,{position:'open',energized:null}).includes('M32 84 H68'),'Ground switches include a fixed earth reference');
const transformer=create('Transformer');
check((E.markup('Transformer',transformer.properties,{energized:null}).match(/<circle/g)||[]).length===2,'Transformer symbol contains both winding circles');
c.properties.energizedChannel=204; c.properties.tripChannel=0;
check(E.channels(c,'CircuitBreaker').length===1,'Shared current reads deduplicate configured feedback channels');
console.log(`Completed: ${checks} electrical checks passed.`);
