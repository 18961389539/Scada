test('duplicate, delete and save shortcuts respect text inputs and preserve optimistic conflicts', async ({ page }) => {
  const state = await fixture(page)
  await openEditor(page)
  await control(page, 'region-title').fill('原始标题')
  await page.keyboard.press('Control+d')
  await expect(control(page, 'layout-region')).toHaveCount(1)
  await control(page, 'region-title').press('Delete')
  await expect(control(page, 'layout-region')).toHaveCount(1)
  await control(page, 'layout-region').focus(); await page.keyboard.press('Control+d')
  await expect(control(page, 'layout-region')).toHaveCount(2)
  await expect(control(page, 'region-title')).toHaveValue('原始标题')
  await page.keyboard.press('Delete')
  await expect(control(page, 'layout-region')).toHaveCount(1)
  await control(page, 'layout-region').focus(); await page.keyboard.press('Backspace')
  await expect(control(page, 'layout-region')).toHaveCount(1)
  state.conflict = true
  await control(page, 'region-title').fill('快捷保存的标题')
  await page.keyboard.press('Control+s')
  await expect(control(page, 'layout-save-error')).toContainText('服务器草稿已更新')
  await expect(control(page, 'layout-save')).toBeDisabled()
  await page.keyboard.press('Control+s')
  await expect(control(page, 'region-title')).toHaveValue('快捷保存的标题')
  expect(state.saved).toHaveLength(1)
  expect(state.saved[0]).toMatchObject({ revision: 7, document: { monitors: [{ regions: [{ title: '快捷保存的标题' }] }, {}] } })
  expect(state.publications).toBe(0)
})

for (const scenario of ['full', 'limit', 'small'] as const) {
  test(`paste and duplicate cannot create overlap or exceed limits when target is ${scenario}`, async ({ page }) => {
    const source = monitor('来源', [region('x'.repeat(40))])
    const target = scenario === 'full' ? monitor('目标', [region('left', { rowSpan: 4, colSpan: 3 })])
      : scenario === 'limit' ? { ...monitor('目标', Array.from({ length: 16 }, (_, i) => region(`r${i}`, { row: 1, col: 1, rowSpan: 1, colSpan: 1 }))), rows: 24, columns: 24 }
      : { ...monitor('目标', []), columns: 1, rows: 1 }
    const state = await fixture(page, [source, target])
    await openEditor(page)
    await control(page, 'layout-copy-region').click()
    await page.getByRole('tab', { name: /目标/ }).click()
    await expect(control(page, 'layout-paste-region')).toBeDisabled()
    const undo = control(page, 'layout-undo')
    await expect(undo).toBeDisabled()
    await page.keyboard.press('Control+v')
    await expect(undo).toBeDisabled()
    await expect(control(page, 'layout-region')).toHaveCount(target.regions.length)
    expect(state.saved).toHaveLength(0)
    await page.getByRole('tab', { name: '来源', exact: true }).click()
    await control(page, 'layout-duplicate-region').click()
    await expect(control(page, 'region-id')).toHaveValue('x'.repeat(35) + '_copy')
    await control(page, 'layout-undo').click()
    await expect(control(page, 'layout-region')).toHaveCount(1)
  })
}

