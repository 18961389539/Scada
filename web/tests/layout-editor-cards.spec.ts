  await control(page, 'layout-paste-region').click()
  await expect(control(page, 'region-id')).toHaveValue('pump_copy2')
  await expect(control(page, 'region-row').locator('input')).toHaveValue('3')
  await control(page, 'layout-undo').click()
  await expect(control(page, 'layout-region')).toHaveCount(2)
  await control(page, 'layout-redo').click()
